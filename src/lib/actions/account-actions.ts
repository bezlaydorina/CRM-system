export async function moveAccountStage(accountId: string, newStage: string) {
  await requireStaffSession();
  const valid = ACCOUNT_LIFECYCLE_STAGES.some((s) => s.key === newStage);
  if (!valid) return;

  const account = await prisma.account.findUnique({ where: { id: accountId } });
  if (!account) return;

  await prisma.account.update({
    where: { id: accountId },
    data: {
      lifecycleStage: newStage,
      lifecycleEnteredAt: new Date(),
      status: newStage === "LOST" ? "ARCHIVED" : account.status,
    },
  });

  await prisma.activityLogEntry.create({
    data: {
      accountId,
      type: "UPDATED",
      message: `Ügyfél átkerült a "${ACCOUNT_LIFECYCLE_STAGES.find((s) => s.key === newStage)?.label}" szakaszba`,
    },
  });

  revalidatePath("/admin/ugyfelek");
  revalidatePath(`/admin/ugyfelek/${accountId}`);
}

function buildPrimaryContactData(formData: FormData) {
  const firstName = String(formData.get("contactFirstName") ?? "").trim();
  const lastName = String(formData.get("contactLastName") ?? "").trim();
  const email = String(formData.get("email") ?? "").trim().toLowerCase();
  const fullName = [lastName, firstName].filter(Boolean).join(" ").trim();
  return { firstName, lastName, email, fullName };
}

async function sendPortalWelcomeEmail(contact: { id: string; fullName: string; email: string | null }, accountName: string, alreadyHasPassword: boolean) {
  if (!contact.email) return;
  if (alreadyHasPassword) {
    await sendEmail({
      to: contact.email,
      subject: `Elkészült a(z) ${accountName} ügyfélportálja`,
      html: portalReadyEmail({ contactName: contact.fullName, accountName, loginUrl: `${getAppUrl()}/portal/login` }),
    });
  } else {
    const setupUrl = await createPortalSetupToken(contact.id);
    await sendEmail({
      to: contact.email,
      subject: `Meghívó – ${accountName} ügyfélportál`,
      html: portalInviteEmail({ contactName: contact.fullName, accountName, setupUrl }),
    });
  }
}

async function createOnboardingTask(session: { organizationId: string; teamMemberId: string }, accountId: string, accountName: string, description: string) {
  await prisma.task.create({
    data: {
      organizationId: session.organizationId,
      accountId,
      title: `Új ügyfeled van: ${accountName}`,
      description,
      category: "Egyéb",
      priority: "MEDIUM",
      assigneeId: session.teamMemberId,
      statusColumn: "ASSIGNED",
      autoGenerated: true,
    },
  });
}

/** Gyorsmentés: csak az alap ügyfél- és kapcsolattartó-adatokat menti el, a csomag/pénzügy később pótolható. */
export async function quickSaveAccountAction(formData: FormData) {
  const session = await requireStaffSession();
  const name = String(formData.get("name") ?? "").trim();
  const { email, fullName } = buildPrimaryContactData(formData);
  if (!name || !email) return;

  const account = await prisma.account.create({
    data: {
      organizationId: session.organizationId,
      name,
      website: String(formData.get("website") ?? "") || null,
      industry: String(formData.get("industry") ?? "") || null,
    },
  });

  await createDefaultCrmSetup(account.id);

  const password = String(formData.get("password") ?? "");
  const setPassword = formData.get("setPassword") === "on" && password.length >= 4;

  const contact = await prisma.contact.create({
    data: {
      accountId: account.id,
      fullName: fullName || name,
      email,
      phone: String(formData.get("phone") ?? "") || null,
      isPrimary: true,
      canLoginPortal: setPassword,
      passwordHash: setPassword ? await hashPassword(password) : null,
    },
  });

  await sendPortalWelcomeEmail(contact, account.name, setPassword);
  await createOnboardingTask(session, account.id, account.name, "Gyorsmentésből jött – vedd fel a kapcsolatot, és pótold a csomagot/pénzügyi adatokat.");

  await prisma.activityLogEntry.create({
    data: { accountId: account.id, type: "CREATED", message: "Ügyfél létrehozva (gyorsmentés)" },
  });

  revalidatePath("/admin/ugyfelek");
  redirect(`/admin/ugyfelek/${account.id}`);
}

/** Teljes létrehozás: a kiválasztott csomag (vagy a Next Level egyedi ajánlata) alapján kiszámolt díjakkal. */
export async function createFullAccountAction(formData: FormData) {
  const session = await requireStaffSession();
  const name = String(formData.get("name") ?? "").trim();
  const { email, fullName } = buildPrimaryContactData(formData);
  if (!name || !email || !fullName) return;

  const pkg = ACCOUNT_PACKAGES.find((p) => p.key === String(formData.get("package") ?? "")) ?? null;

  const monthlyFee = pkg?.custom ? Number(formData.get("customMonthlyFee") ?? 0) : pkg?.monthlyFee ?? 0;
  const setupFee = pkg?.custom ? Number(formData.get("customSetupFee") ?? 0) : pkg?.setupFee ?? 0;

  const contractSignedRaw = String(formData.get("contractSignedAt") ?? "");
  const contractSignedAt = contractSignedRaw ? new Date(contractSignedRaw) : null;

  const account = await prisma.account.create({
    data: {
      organizationId: session.organizationId,
      name,
      website: String(formData.get("website") ?? "") || null,
      industry: String(formData.get("industry") ?? "") || null,
      monthlyFee,
      setupFee,
      contractSignedAt,
      package: pkg?.key ?? null,
    },
  });

  await createDefaultCrmSetup(account.id);

  const password = String(formData.get("password") ?? "");
  const setPassword = formData.get("setPassword") === "on" && password.length >= 4;

  const contact = await prisma.contact.create({
    data: {
      accountId: account.id,
      fullName,
      email,
      phone: String(formData.get("phone") ?? "") || null,
      isPrimary: true,
      canLoginPortal: setPassword,
      passwordHash: setPassword ? await hashPassword(password) : null,
    },
  });

  await sendPortalWelcomeEmail(contact, account.name, setPassword);

  if (contractSignedAt) {
    await prisma.contract.create({
      data: { accountId: account.id, status: "SIGNED", amount: setupFee, templateName: "Alap szolgáltatási szerződés", signedAt: contractSignedAt },
    });
    await prisma.payment.create({
      data: {
        accountId: account.id,
        amount: setupFee,
        type: "ONE_TIME",
        status: "CREATED",
        dueDate: contractSignedAt,
      },
    });
  }

  const projectNote = String(formData.get("projectNote") ?? "").trim();
  const internalNote = String(formData.get("internalNote") ?? "").trim();
  const noteBody = [projectNote && `Projekt igény: ${projectNote}`, internalNote].filter(Boolean).join("\n\n");
  if (noteBody) {
    await prisma.activityLogEntry.create({
      data: { accountId: account.id, actorId: session.teamMemberId, type: "NOTE_ADDED", message: noteBody },
    });
  }

  await createOnboardingTask(session, account.id, account.name, "Vedd fel a kapcsolatot és indítsd el az onboardingot.");

  await prisma.activityLogEntry.create({
    data: { accountId: account.id, type: "CREATED", message: `Ügyfél létrehozva${pkg ? ` (${pkg.label} csomag)` : ""}` },
  });

  revalidatePath("/admin/ugyfelek");
  revalidatePath("/admin/fizetesek");
  revalidatePath("/admin/szerzodesek");
  redirect(`/admin/ugyfelek/${account.id}`);
}

export async function updateAccountDetailsAction(accountId: string, formData: FormData) {
  await requireStaffSession();

  const data: Record<string, unknown> = {};
  for (const key of ["website", "industry", "source"] as const) {
    const v = formData.get(key);
    if (v !== null) data[key] = String(v) || null;
  }
  for (const key of ["monthlyFee", "setupFee"] as const) {
    const v = formData.get(key);
    if (v !== null) data[key] = Number(v);
  }
  if (formData.has("isTestAccountField")) {
    data.isTestAccount = formData.get("isTestAccount") === "on";
  }

  await prisma.account.update({ where: { id: accountId }, data });
  revalidatePath(`/admin/ugyfelek/${accountId}`);
}

