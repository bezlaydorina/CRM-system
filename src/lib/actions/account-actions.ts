export async function changePortalPasswordAction(accountId: string, formData: FormData) {
  await requireStaffSession();
  const contactId = String(formData.get("contactId") ?? "");
  const newPassword = String(formData.get("newPassword") ?? "");
  if (!contactId || newPassword.length < 4) return;
  const hash = await hashPassword(newPassword);
  await prisma.contact.update({ where: { id: contactId }, data: { passwordHash: hash, canLoginPortal: true } });
  revalidatePath(`/admin/ugyfelek/${accountId}`);
}

export async function addContactAction(accountId: string, formData: FormData) {
  await requireStaffSession();
  const fullName = String(formData.get("fullName") ?? "").trim();
  if (!fullName) return;
  await prisma.contact.create({
    data: {
      accountId,
      fullName,
      email: String(formData.get("email") ?? "") || null,
      phone: String(formData.get("phone") ?? "") || null,
      position: String(formData.get("position") ?? "") || null,
      isPrimary: false,
    },
  });
  revalidatePath(`/admin/ugyfelek/${accountId}`);
}

export async function setTeamAssignmentAction(accountId: string, formData: FormData) {
  await requireStaffSession();
  const role = String(formData.get("role") ?? "");
  const teamMemberId = String(formData.get("teamMemberId") ?? "");
  if (!role) return;

  await prisma.teamAssignment.deleteMany({ where: { accountId, role } });
  if (teamMemberId) {
    await prisma.teamAssignment.create({ data: { accountId, role, teamMemberId } });
  }
  revalidatePath(`/admin/ugyfelek/${accountId}`);
}

